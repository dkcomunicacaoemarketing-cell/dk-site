module.exports = async function handler(req, res) {
  if (req.method !== "POST") {
    res.status(405).json({ error: "method_not_allowed" });
    return;
  }

  let body = req.body;

  if (typeof body === "string") {
    try {
      body = JSON.parse(body);
    } catch {
      res.status(400).json({ error: "invalid_json" });
      return;
    }
  }

  const messages = body && Array.isArray(body.messages) ? body.messages : null;

  if (!messages) {
    res.status(400).json({ error: "messages_required" });
    return;
  }

  const safeMessages = messages
    .filter(
      (m) =>
        m &&
        (m.role === "user" || m.role === "assistant") &&
        typeof m.content === "string"
    )
    .slice(-20)
    .map((m) => ({
      role: m.role,
      content: m.content.slice(0, 4000),
    }));

  if (safeMessages.length === 0) {
    res.status(400).json({ error: "messages_required" });
    return;
  }

  // Modo "finalizar": não chama a IA de conversa, gera o resumo e manda pro Daniel.
  if (body.finalizar === true) {
    const totalMensagens = safeMessages.filter((m) => m.role === "user").length;

    if (totalMensagens === 0) {
      res.status(200).json({ ok: true, skipped: true });
      return;
    }

    const motivo = typeof body.motivo === "string" ? body.motivo : "desconhecido";
    const email = extrairEmail(safeMessages);
    const orcamento = pediuOrcamento(safeMessages);
    const resumoCompleto = criarResumo(safeMessages);
    const resumoIA = await gerarResumoIA(safeMessages);

    const resultadoEnvio = await enviarEmailParaDaniel({
      nome: resumoIA?.nome || extrairNome(safeMessages),
      email,
      assunto: resumoIA?.assunto || identificarInteresse(safeMessages),
      mensagem: resumoIA?.mensagem,
      parecer: resumoIA?.parecer,
      pediuOrcamento: orcamento,
      motivo,
      resumoCompleto,
    });

    // A resposta agora sempre traz o motivo real quando falha,
    // visível direto no Network tab do navegador.
    res.status(200).json({
      ok: true,
      emailSent: resultadoEnvio.ok,
      emailError: resultadoEnvio.ok ? null : resultadoEnvio.motivo,
    });
    return;
  }

  // Modo normal: conversa com a IA.
  const apiKey = process.env.OPENROUTER_API_KEY;

  if (!apiKey) {
    console.error("OPENROUTER_API_KEY não configurada no ambiente do Vercel.");
    res.status(500).json({ error: "server_misconfigured" });
    return;
  }

  try {
    const upstream = await fetch("https://openrouter.ai/api/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${apiKey}`,
        "HTTP-Referer": "https://dkmarketingpolitico.com.br",
        "X-Title": "DK Marketing Político",
      },
      body: JSON.stringify({
        model: MODEL,
        messages: [{ role: "system", content: SYSTEM_PROMPT }, ...safeMessages],
        temperature: 0.6,
        max_tokens: 450,
      }),
    });

    if (!upstream.ok) {
      const errText = await upstream.text();
      console.error("OpenRouter error:", upstream.status, errText);
      res.status(502).json({ error: "upstream_error" });
      return;
    }

    const data = await upstream.json();
    const content = data.choices?.[0]?.message?.content ?? "";

    res.status(200).json({ content });
  } catch (err) {
    console.error("Erro ao chamar OpenRouter:", err);
    res.status(500).json({ error: "internal_error" });
  }
};
